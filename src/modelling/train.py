"""Train the title and thumbnail models from the processed table.

    python -m src.modelling.train            # both
    python -m src.modelling.train title
    python -m src.modelling.train thumbnail --folds 5

Reads data/processed/videos.parquet, derives the target (src/scoring/target),
extracts each model's features, fits with channel-grouped cross-validation,
and saves to models/<name>/ with a JSON model card. Thumbnail features are
cached in data/processed/features_thumbnail.parquet keyed by video id, so a
retrain after a code change elsewhere does not re-read every image.
"""

import argparse
import math
from pathlib import Path
from typing import Callable, Dict, List, Optional

import pandas as pd

from config.schema import (
    CONTENT_TYPE,
    SUBSCRIBER_COUNT,
    MODELS_DIR,
    PROCESSED_DIR,
    REACH,
    THUMBNAIL_FILE,
    THUMBNAILS_DIR,
    TITLE,
    VIDEO_ID,
    VIDEOS_TABLE,
    VIDEOS_TABLE_CSV,
)
from src.data.synthetic import is_synthetic
from src.modelling.model import ReachModel, TrainingReport, build_feature_frame
from src.scoring.target import add_target

TITLE_MODEL = "title"
THUMBNAIL_MODEL = "thumbnail"


def load_table(processed_dir: Path = PROCESSED_DIR) -> pd.DataFrame:
    parquet = processed_dir / VIDEOS_TABLE.name
    csv = processed_dir / VIDEOS_TABLE_CSV.name
    if parquet.exists():
        return pd.read_parquet(parquet)
    if csv.exists():
        return pd.read_csv(csv)
    raise FileNotFoundError(
        f"no processed table in {processed_dir}. Run `python -m src.collection all` "
        "with an API key, or `python -m src.data.synthetic` for a stand-in."
    )


def data_source_label(processed_dir: Path = PROCESSED_DIR) -> str:
    return "synthetic" if is_synthetic(processed_dir.parent) else "collected"


def title_features(table: pd.DataFrame) -> pd.DataFrame:
    from src.title.features import TITLE_FEATURES, extract_title_features

    return build_feature_frame(
        table, lambda r: extract_title_features(r[TITLE], r[CONTENT_TYPE], r[SUBSCRIBER_COUNT]), TITLE_FEATURES
    )


def thumbnail_features(
    table: pd.DataFrame, thumbnails_dir: Path = THUMBNAILS_DIR, cache: Optional[Path] = None, log=print
) -> pd.DataFrame:
    from src.thumbnail.features import FEATURE_VERSION, THUMBNAIL_FEATURES, extract_thumbnail_features

    cached = pd.DataFrame()
    if cache is not None and cache.exists():
        cached = pd.read_parquet(cache)
        if cached.attrs.get("feature_version", None) != FEATURE_VERSION and "_version" in cached.columns:
            cached = cached[cached["_version"] == FEATURE_VERSION]
        cached = cached.set_index(VIDEO_ID) if VIDEO_ID in cached.columns else pd.DataFrame()

    rows: List[Dict[str, float]] = []
    new_rows = 0
    for i, (_, r) in enumerate(table.iterrows(), 1):
        vid = r[VIDEO_ID]
        if len(cached) and vid in cached.index and not cached.loc[vid, "image_missing"]:
            feats = cached.loc[vid, THUMBNAIL_FEATURES].to_dict()
            # content type one-hots come from the table, never the cache
            feats = {k: v for k, v in feats.items() if not k.startswith("ct_") and k != "log_subscribers"}
            feats["log_subscribers"] = math.log10(r[SUBSCRIBER_COUNT]) if r[SUBSCRIBER_COUNT] > 0 else float("nan")
            feats.update({"ct_" + ct: float(r[CONTENT_TYPE] == ct) for ct in [c[3:] for c in THUMBNAIL_FEATURES if c.startswith("ct_")]})
        else:
            path = thumbnails_dir / r[THUMBNAIL_FILE] if r[THUMBNAIL_FILE] else None
            feats = extract_thumbnail_features(path, r[CONTENT_TYPE], r[SUBSCRIBER_COUNT])
            new_rows += 1
        feats[VIDEO_ID] = vid
        rows.append(feats)
        if i % 500 == 0:
            log(f"  {i}/{len(table)} thumbnails")
    frame = pd.DataFrame(rows)
    if cache is not None and new_rows:
        out = frame.copy()
        out["_version"] = FEATURE_VERSION
        cache.parent.mkdir(parents=True, exist_ok=True)
        out.to_parquet(cache, index=False)
    for name in THUMBNAIL_FEATURES:
        if name not in frame.columns:
            frame[name] = 0.0
    frame = frame[THUMBNAIL_FEATURES].astype(float)
    non_context = [c for c in THUMBNAIL_FEATURES if c != "log_subscribers"]
    frame[non_context] = frame[non_context].fillna(0.0)
    return frame


def train_one(
    name: str,
    table: pd.DataFrame,
    features: pd.DataFrame,
    feature_version: str,
    age_slope: float,
    data_source: str,
    folds: int = 5,
    models_dir: Path = MODELS_DIR,
    log=print,
) -> TrainingReport:
    model = ReachModel(name)
    report = model.fit(features, table, data_source, feature_version, age_slope, folds=folds)
    if data_source == "synthetic":
        report.notes.append(
            "Trained on SYNTHETIC data generated by src/data/synthetic.py. "
            "Scores reflect the generator's rules, not YouTube."
        )
    path = model.save(models_dir)
    log(f"\n{name} model -> {path}")
    log(f"  rows {report.rows:,}  channels {report.channels}  folds {report.folds}  backend {report.backend}")
    log(f"  out-of-fold spearman {report.spearman:.3f}  r2 {report.r2:.3f}  "
        f"mae {report.mae:.3f} (baseline {report.baseline_mae:.3f})")
    for ct, m in report.per_content_type.items():
        log(f"    {ct:<10} rows {m['rows']:>5}  spearman {m['spearman']:.3f}")
    top = list(report.importance.items())[:8]
    log("  top features: " + ", ".join(f"{k} {v:.2f}" for k, v in top))
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("which", nargs="?", choices=[TITLE_MODEL, THUMBNAIL_MODEL, "both"], default="both")
    parser.add_argument("--folds", type=int, default=5)
    parser.add_argument("--no-cache", action="store_true", help="re-extract every thumbnail")
    args = parser.parse_args(argv)

    table = load_table()
    source = data_source_label()
    table, slope = add_target(table)
    print(f"{len(table):,} videos ({source}), age slope {slope:.3f}")

    if args.which in (TITLE_MODEL, "both"):
        from src.title.features import FEATURE_VERSION as title_version

        feats = title_features(table)
        train_one(TITLE_MODEL, table, feats, title_version, slope, source, args.folds)

    if args.which in (THUMBNAIL_MODEL, "both"):
        from src.thumbnail.features import FEATURE_VERSION as thumb_version

        has_image = table[THUMBNAIL_FILE].astype(str).str.len() > 0
        sub = table[has_image].reset_index(drop=True)
        print(f"\nextracting thumbnail features for {len(sub):,} images")
        cache = None if args.no_cache else PROCESSED_DIR / "features_thumbnail.parquet"
        feats = thumbnail_features(sub, cache=cache)
        ok = feats["image_missing"] == 0
        print(f"  {int((~ok).sum())} images missing or unreadable, dropped")
        train_one(THUMBNAIL_MODEL, sub[ok].reset_index(drop=True), feats[ok].reset_index(drop=True),
                  thumb_version, slope, source, args.folds)


if __name__ == "__main__":
    main()
